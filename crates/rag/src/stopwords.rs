/// Palabras vacías en inglés, por si el corpus mezcla idiomas.
const ENGLISH: &[&str] = &[
    "a", "an", "and", "are", "as", "at", "be", "by", "for", "from", "has", "have", "in", "is",
    "it", "its", "of", "on", "or", "that", "the", "their", "this", "to", "was", "were", "which",
    "with",
];

fn set() -> &'static HashSet<&'static str> {
    static SET: OnceLock<HashSet<&'static str>> = OnceLock::new();
    SET.get_or_init(|| SPANISH.iter().chain(ENGLISH).copied().collect())
}

/// ¿La palabra es vacía y debe ignorarse al indexar y al buscar?
pub fn is_stopword(token: &str) -> bool {
    set().contains(token)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reconoce_palabras_vacias_frecuentes() {
        for token in ["de", "la", "que", "para", "the", "of"] {
            assert!(is_stopword(token), "«{token}» debería ser vacía");
        }
        for token in ["facturacion", "servidor", "indexacion", "bm25"] {
            assert!(!is_stopword(token), "«{token}» no debería ser vacía");
        }
    }
}
